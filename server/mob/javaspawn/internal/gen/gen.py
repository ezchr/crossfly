#!/usr/bin/env python3
# Generates server/mob/javaspawn/data_gen.go from the vanilla 26.3 data and
# the decompiled EntityTypes.java. Usage: gen.py <out.go>
import json, os, re, sys, glob

DATA = '/root/javaproto/refs/mojang-26.3/builtin/data/minecraft'
ENT = '/root/javaproto/decomp/v26x/26.3/src/net/minecraft/world/entity/EntityTypes.java'
IDS = '/root/javaproto/decomp/v26x/26.3/src/net/minecraft/world/entity/EntityTypeIds.java'

CATS = ['monster', 'creature', 'ambient', 'axolotls', 'underground_water_creature',
        'water_creature', 'water_ambient', 'misc']
CATCONST = {c: 'Category' + ''.join(p.capitalize() for p in c.split('_')) for c in CATS}

def strip(n):
    return n[len('minecraft:'):] if n.startswith('minecraft:') else n

# ---- block tags ----
_tagcache = {}
def tag(kind, name):
    key = (kind, name)
    if key in _tagcache:
        return _tagcache[key]
    path = f'{DATA}/tags/{kind}/{name}.json'
    out = []
    for v in json.load(open(path))['values']:
        if isinstance(v, dict):
            if not v.get('required', True) and v['id'].startswith('#'):
                continue
            v = v['id']
        if v.startswith('#'):
            out += tag(kind, strip(v[1:]))
        else:
            out.append(strip(v))
    out = sorted(set(out))
    _tagcache[key] = out
    return out

BLOCK_TAGS = ['animals_spawnable_on', 'mooshrooms_spawnable_on', 'frogs_spawnable_on',
              'axolotls_spawnable_on', 'parrots_spawnable_on', 'rabbits_spawnable_on',
              'foxes_spawnable_on', 'armadillo_spawnable_on', 'wolves_spawnable_on',
              'goats_spawnable_on', 'camels_spawnable_on', 'bats_spawnable_on',
              'polar_bears_spawnable_on_alternate', 'prevent_mob_spawning_inside', 'fire',
              'leaves', 'sand', 'default_immune_to', 'fox_immune_to', 'polar_bear_immune_to',
              'snow_golem_immune_to', 'stray_immune_to', 'wither_immune_to',
              'wither_skeleton_immune_to']
BIOME_TAGS = ['allows_surface_slime_spawns', 'allows_tropical_fish_spawns_at_any_height',
              'more_frequent_drowned_spawns', 'polar_bears_spawn_on_alternate_blocks',
              'reduce_water_ambient_spawns']

# ---- entity types ----
ids = {}
for m in re.finditer(r'public static final ResourceKey<EntityType<\?>> (\w+) = create\("([\w/]+)"\)', open(IDS).read()):
    ids[m.group(1)] = m.group(2)
src = open(ENT).read()
types = []
for m in re.finditer(r'register\(\s*EntityTypeIds\.(\w+),(.*?)\n   \);', src, re.S):
    const, body = m.group(1), m.group(2)
    cm = re.search(r'MobCategory\.(\w+)', body)
    if not cm:
        continue
    sm = re.search(r'\.sized\(([\d.]+)F, ([\d.]+)F\)', body)
    w, h = (float(sm.group(1)), float(sm.group(2))) if sm else (0.6, 1.8)  # Builder default sized(0.6F, 1.8F)
    im = re.search(r'\.immuneTo\(BlockTags\.(\w+)\)', body)
    immune = im.group(1).lower() if im else 'default_immune_to'
    types.append(dict(id=ids.get(const, const.lower()), cat=cm.group(1).lower(), w=w, h=h,
                      fire='.fireImmune()' in body, peaceful='.notInPeaceful()' not in body,
                      far='.canSpawnFarFromPlayer()' in body, summon='.noSummon()' not in body,
                      immune=immune))

# ---- biomes ----
def count(c):
    if isinstance(c, int):
        return c, c
    assert c['type'] == 'minecraft:uniform', c
    return c['min_inclusive'], c['max_inclusive']

def spawnlist(lst):
    out = []
    for s in lst:
        lo, hi = count(s.get('count', 1))
        out.append((strip(s['type']), s['weight'], lo, hi))
    return out

biomes = {}
for f in sorted(glob.glob(f'{DATA}/worldgen/biome/*.json')):
    name = os.path.basename(f)[:-5]
    d = json.load(open(f))
    nms = d.get('attributes', {}).get('minecraft:gameplay/natural_mob_spawns')
    cats, costs = {}, {}
    if nms:
        arg = nms['argument'] if 'argument' in nms else nms
        for c, lst in arg.get('spawns_by_category', {}).items():
            cats[c] = spawnlist(lst)
        for t, c in arg.get('spawn_costs', {}).items():
            costs[strip(t)] = (c['charge'], c['energy_budget'])
    biomes[name] = (cats, costs)

structs = {}
for f in sorted(glob.glob(f'{DATA}/worldgen/structure/*.json')):
    name = os.path.basename(f)[:-5]
    so = json.load(open(f)).get('spawn_overrides')
    if so:
        structs[name] = {c: (o['bounding_box'], spawnlist(o['spawns'])) for c, o in so.items()}

def golist(xs):
    return '[]string{' + ', '.join(f'"{x}"' for x in xs) + '}'

def spawners(lst):
    return '[]Spawner{' + ', '.join(f'{{"minecraft:{t}", {w}, {lo}, {hi}}}' for t, w, lo, hi in lst) + '}'

o = []
o.append('// Code generated by gen.py from the vanilla 26.3 data (worldgen/biome, worldgen/structure,')
o.append('// tags) and the decompiled net.minecraft.world.entity.EntityTypes. DO NOT EDIT.\n')
o.append('//go:build crossfly_full\n')
o.append('package javaspawn\n')
o.append('// entityTypes are the EntityType.Builder settings of every 26.3 entity type with a')
o.append('// MobCategory (EntityTypes.register): category, sized(), fireImmune(), notInPeaceful(),')
o.append('// canSpawnFarFromPlayer(), noSummon() and immuneTo().')
o.append('var entityTypes = map[string]*EntityType{')
for t in types:
    o.append(f'\t"minecraft:{t["id"]}": {{ID: "minecraft:{t["id"]}", Category: {CATCONST[t["cat"]]}, Width: {t["w"]}, Height: {t["h"]}, '
             f'FireImmune: {str(t["fire"]).lower()}, AllowedInPeaceful: {str(t["peaceful"]).lower()}, '
             f'CanSpawnFarFromPlayer: {str(t["far"]).lower()}, CanSummon: {str(t["summon"]).lower()}, ImmuneTo: "{t["immune"]}"}},')
o.append('}\n')
o.append('// blockTags are the 26.3 block tags spawning reads, resolved to Java block names.')
o.append('var blockTags = map[string][]string{')
for b in BLOCK_TAGS:
    o.append(f'\t"{b}": {golist(tag("block", b))},')
o.append('}\n')
o.append('// biomeTags are the 26.3 biome tags spawning reads (Java biome names).')
o.append('var biomeTags = map[string][]string{')
for b in BIOME_TAGS:
    o.append(f'\t"{b}": {golist(tag("worldgen/biome", b))},')
o.append('}\n')
o.append('// biomeSpawns is gameplay/natural_mob_spawns of every 26.3 biome: spawners_by_category')
o.append('// and spawn_costs (MobSpawnSettings).')
o.append('var biomeSpawns = map[string]*MobSpawnSettings{')
for name, (cats, costs) in biomes.items():
    parts = []
    for c in CATS:
        if c in cats and cats[c]:
            parts.append(f'{CATCONST[c]}: {spawners(cats[c])}')
    cs = ', '.join(f'"minecraft:{t}": {{{ch}, {eb}}}' for t, (ch, eb) in sorted(costs.items()))
    o.append(f'\t"{name}": {{Spawns: [numCategories][]Spawner{{{", ".join(parts)}}}, Costs: map[string]SpawnCost{{{cs}}}}},')
o.append('}\n')
o.append('// structureOverrides are the spawn_overrides of the 26.3 structures (StructureSpawnOverride).')
o.append('var structureOverrides = map[string]map[Category]StructureOverride{')
for name, so in structs.items():
    parts = ', '.join(f'{CATCONST[c]}: {{Piece: {str(bb == "piece").lower()}, Spawns: {spawners(lst)}}}' for c, (bb, lst) in so.items())
    o.append(f'\t"{name}": {{{parts}}},')
o.append('}')
open(sys.argv[1], 'w').write('\n'.join(o) + '\n')
print(len(types), 'types', len(biomes), 'biomes', len(structs), 'structures')
